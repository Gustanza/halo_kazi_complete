--------------------------------------------------------------------------------
-- HALOKAZI - Oracle 19c schema
-- Web-Based CV Builder, Career & Job Opportunity Platform (Halotel, in-house)
--
-- Run order: 01_schema.sql -> 02_logic.sql -> 03_seed_reference.sql
-- Conventions
--   * Booleans are NUMBER(1) with CHECK (0/1)        (19c has no BOOLEAN column)
--   * JSON is stored in CLOB with CHECK (col IS JSON)  (19c has no JSON type)
--   * Timestamps are TIMESTAMP WITH TIME ZONE; the app displays them in EAT (UTC+3)
--   * Status/enumeration columns are VARCHAR2 + CHECK; translatable lists are lookup tables
--   * Oracle does not index foreign keys automatically, so FK indexes are created explicitly
--   * Reserved words avoided: USER -> APP_USER, LANGUAGE -> SPOKEN_LANGUAGE,
--     REPORT (moderation) -> USER_REPORT to avoid confusion with analytics reports
--------------------------------------------------------------------------------

--==============================================================================
-- 1. REFERENCE / LOOKUP DATA  (bilingual: name_en / name_sw)
--==============================================================================

CREATE TABLE region (
    region_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code             VARCHAR2(30)  NOT NULL,
    name_en          VARCHAR2(100) NOT NULL,
    name_sw          VARCHAR2(100) NOT NULL,
    zone             VARCHAR2(20)  DEFAULT 'MAINLAND' NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_region PRIMARY KEY (region_id),
    CONSTRAINT uq_region_code UNIQUE (code),
    CONSTRAINT ck_region_zone CHECK (zone IN ('MAINLAND', 'ZANZIBAR')),
    CONSTRAINT ck_region_active CHECK (is_active IN (0, 1))
);

CREATE TABLE district (
    district_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    region_id        NUMBER        NOT NULL,
    name_en          VARCHAR2(100) NOT NULL,
    name_sw          VARCHAR2(100) NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_district PRIMARY KEY (district_id),
    CONSTRAINT fk_district_region FOREIGN KEY (region_id) REFERENCES region (region_id),
    CONSTRAINT uq_district_name UNIQUE (region_id, name_en),
    CONSTRAINT ck_district_active CHECK (is_active IN (0, 1))
);
CREATE INDEX ix_district_region ON district (region_id);

CREATE TABLE job_category (
    category_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code             VARCHAR2(40)  NOT NULL,
    name_en          VARCHAR2(100) NOT NULL,
    name_sw          VARCHAR2(100) NOT NULL,
    sort_order       NUMBER(4)     DEFAULT 0 NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_job_category PRIMARY KEY (category_id),
    CONSTRAINT uq_job_category_code UNIQUE (code),
    CONSTRAINT ck_job_category_active CHECK (is_active IN (0, 1))
);

CREATE TABLE employment_type (
    employment_type_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code             VARCHAR2(30)  NOT NULL,
    name_en          VARCHAR2(60)  NOT NULL,
    name_sw          VARCHAR2(60)  NOT NULL,
    sort_order       NUMBER(4)     DEFAULT 0 NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_employment_type PRIMARY KEY (employment_type_id),
    CONSTRAINT uq_employment_type_code UNIQUE (code),
    CONSTRAINT ck_employment_type_active CHECK (is_active IN (0, 1))
);

-- Ordered levels (sort_order) let rule-based matching compare "minimum education".
CREATE TABLE education_level (
    education_level_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code             VARCHAR2(30)  NOT NULL,
    name_en          VARCHAR2(80)  NOT NULL,
    name_sw          VARCHAR2(80)  NOT NULL,
    sort_order       NUMBER(4)     NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_education_level PRIMARY KEY (education_level_id),
    CONSTRAINT uq_education_level_code UNIQUE (code),
    CONSTRAINT ck_education_level_active CHECK (is_active IN (0, 1))
);

CREATE TABLE skill (
    skill_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    name_en          VARCHAR2(100) NOT NULL,
    name_sw          VARCHAR2(100),
    category_id      NUMBER,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_skill PRIMARY KEY (skill_id),
    CONSTRAINT fk_skill_category FOREIGN KEY (category_id) REFERENCES job_category (category_id),
    CONSTRAINT ck_skill_active CHECK (is_active IN (0, 1))
);
CREATE UNIQUE INDEX uq_skill_name ON skill (LOWER(name_en));
CREATE INDEX ix_skill_category ON skill (category_id);

CREATE TABLE spoken_language (
    language_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    iso_code         VARCHAR2(10)  NOT NULL,
    name_en          VARCHAR2(60)  NOT NULL,
    name_sw          VARCHAR2(60)  NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_spoken_language PRIMARY KEY (language_id),
    CONSTRAINT uq_spoken_language_iso UNIQUE (iso_code),
    CONSTRAINT ck_spoken_language_active CHECK (is_active IN (0, 1))
);

-- Categories for user reports (fraud, spam, abuse ...)
CREATE TABLE report_reason (
    reason_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code             VARCHAR2(40)  NOT NULL,
    name_en          VARCHAR2(100) NOT NULL,
    name_sw          VARCHAR2(100) NOT NULL,
    applies_to       VARCHAR2(20)  DEFAULT 'ALL' NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_report_reason PRIMARY KEY (reason_id),
    CONSTRAINT uq_report_reason_code UNIQUE (code),
    CONSTRAINT ck_report_reason_applies CHECK (applies_to IN ('ALL', 'EMPLOYER', 'VACANCY', 'JOB_SEEKER')),
    CONSTRAINT ck_report_reason_active CHECK (is_active IN (0, 1))
);

-- Profile completion sections and weights (Requirements section 5). Weights are data, not code.
CREATE TABLE profile_section (
    section_code     VARCHAR2(30)  NOT NULL,
    name_en          VARCHAR2(80)  NOT NULL,
    name_sw          VARCHAR2(80)  NOT NULL,
    weight           NUMBER(5,2)   NOT NULL,
    can_be_na        NUMBER(1)     DEFAULT 0 NOT NULL,
    sort_order       NUMBER(4)     DEFAULT 0 NOT NULL,
    is_active        NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_profile_section PRIMARY KEY (section_code),
    CONSTRAINT ck_profile_section_code CHECK (section_code IN
        ('CONTACT', 'EDUCATION', 'WORK_EXPERIENCE', 'SKILLS', 'CERTIFICATIONS',
         'LANGUAGES', 'ADDRESS', 'SUMMARY', 'PROFILE_PICTURE')),
    CONSTRAINT ck_profile_section_weight CHECK (weight BETWEEN 0 AND 100),
    CONSTRAINT ck_profile_section_na CHECK (can_be_na IN (0, 1)),
    CONSTRAINT ck_profile_section_active CHECK (is_active IN (0, 1))
);

-- Tunable business values (75% threshold, OTP 2 min, 3 resends, 10 min session, 14-day drafts ...)
CREATE TABLE system_setting (
    setting_key      VARCHAR2(60)   NOT NULL,
    setting_value    VARCHAR2(400)  NOT NULL,
    value_type       VARCHAR2(10)   DEFAULT 'STRING' NOT NULL,
    description      VARCHAR2(400),
    updated_by       NUMBER,
    updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_system_setting PRIMARY KEY (setting_key),
    CONSTRAINT ck_system_setting_type CHECK (value_type IN ('STRING', 'NUMBER', 'BOOLEAN'))
);

--==============================================================================
-- 2. USERS, ACCESS & SECURITY
