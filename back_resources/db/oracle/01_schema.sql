CREATE TABLE app_user (
    user_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    full_name          VARCHAR2(150) NOT NULL,
    email              VARCHAR2(254) NOT NULL,
    phone              VARCHAR2(20)  NOT NULL,                 -- E.164, e.g. +2556XXXXXXXX
    password_hash      VARCHAR2(255) NOT NULL,                 -- bcrypt/argon2 output only
    role               VARCHAR2(20)  NOT NULL,
    account_status     VARCHAR2(30)  DEFAULT 'PENDING_VERIFICATION' NOT NULL,
    phone_verified     NUMBER(1)     DEFAULT 0 NOT NULL,
    phone_verified_at  TIMESTAMP WITH TIME ZONE,
    preferred_language VARCHAR2(2)   DEFAULT 'EN' NOT NULL,
    failed_login_count NUMBER(4)     DEFAULT 0 NOT NULL,
    locked_until       TIMESTAMP WITH TIME ZONE,
    last_login_at      TIMESTAMP WITH TIME ZONE,
    password_changed_at TIMESTAMP WITH TIME ZONE,
    suspended_at       TIMESTAMP WITH TIME ZONE,
    suspended_by       NUMBER,
    suspension_reason  VARCHAR2(500),
    created_by         NUMBER,                                 -- Super Admin who created an Admin
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at         TIMESTAMP WITH TIME ZONE,               -- soft delete (AUTH-11)
    anonymized_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT fk_app_user_suspended_by FOREIGN KEY (suspended_by) REFERENCES app_user (user_id),
    CONSTRAINT fk_app_user_created_by FOREIGN KEY (created_by) REFERENCES app_user (user_id),
    CONSTRAINT ck_app_user_role CHECK (role IN ('JOB_SEEKER', 'EMPLOYER', 'ADMIN', 'SUPER_ADMIN')),
    CONSTRAINT ck_app_user_status CHECK (account_status IN
        ('PENDING_VERIFICATION', 'ACTIVE', 'SUSPENDED', 'DEACTIVATED', 'DELETED')),
    CONSTRAINT ck_app_user_phone_verified CHECK (phone_verified IN (0, 1)),
    CONSTRAINT ck_app_user_lang CHECK (preferred_language IN ('EN', 'SW')),
    CONSTRAINT ck_app_user_admin_creator CHECK (role <> 'ADMIN' OR created_by IS NOT NULL),
    CONSTRAINT ck_app_user_deleted CHECK (account_status <> 'DELETED' OR deleted_at IS NOT NULL)
);
-- Case-insensitive uniqueness; anonymisation replaces email/phone with unique placeholders.
CREATE UNIQUE INDEX uq_app_user_email ON app_user (LOWER(email));
CREATE UNIQUE INDEX uq_app_user_phone ON app_user (phone);
CREATE INDEX ix_app_user_role_status ON app_user (role, account_status);

ALTER TABLE system_setting ADD CONSTRAINT fk_system_setting_user
    FOREIGN KEY (updated_by) REFERENCES app_user (user_id);

-- All uploaded/generated files. Bytes live in isolated object storage; DB holds metadata only.
CREATE TABLE stored_file (
    file_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    owner_user_id      NUMBER,
    file_category      VARCHAR2(40)  NOT NULL,
    storage_provider   VARCHAR2(30)  DEFAULT 'OBJECT_STORAGE' NOT NULL,
    storage_key        VARCHAR2(500) NOT NULL,                 -- bucket/path, never a public URL
    original_filename  VARCHAR2(255),
    mime_type          VARCHAR2(100) NOT NULL,
    size_bytes         NUMBER(12)    NOT NULL,
    checksum_sha256    VARCHAR2(64),
    scan_status        VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL,
    scanned_at         TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    deleted_at         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_stored_file PRIMARY KEY (file_id),
    CONSTRAINT fk_stored_file_owner FOREIGN KEY (owner_user_id) REFERENCES app_user (user_id),
    CONSTRAINT uq_stored_file_key UNIQUE (storage_key),
    CONSTRAINT ck_stored_file_category CHECK (file_category IN
        ('PROFILE_PICTURE', 'CERTIFICATE', 'VERIFICATION_DOCUMENT', 'COMPANY_LOGO',
         'CV_PDF', 'APPLICATION_CV_PDF', 'CV_TEMPLATE_PREVIEW', 'REPORT_EXPORT')),
    CONSTRAINT ck_stored_file_scan CHECK (scan_status IN ('PENDING', 'CLEAN', 'INFECTED', 'FAILED', 'NOT_REQUIRED')),
    CONSTRAINT ck_stored_file_size CHECK (size_bytes >= 0)
);
CREATE INDEX ix_stored_file_owner ON stored_file (owner_user_id);
CREATE INDEX ix_stored_file_scan ON stored_file (scan_status);

CREATE TABLE admin_permission (
    permission_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code             VARCHAR2(60)  NOT NULL,
    module           VARCHAR2(40)  NOT NULL,
    name_en          VARCHAR2(100) NOT NULL,
    name_sw          VARCHAR2(100) NOT NULL,
    description      VARCHAR2(400),
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_admin_permission PRIMARY KEY (permission_id),
    CONSTRAINT uq_admin_permission_code UNIQUE (code)
);

-- Grant/revoke history; a row with revoked_at IS NULL is an active grant.
CREATE TABLE admin_permission_assignment (
    assignment_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER NOT NULL,
    permission_id    NUMBER NOT NULL,
    assigned_by      NUMBER NOT NULL,
    assigned_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    revoked_by       NUMBER,
    revoked_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_admin_perm_assignment PRIMARY KEY (assignment_id),
    CONSTRAINT fk_apa_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT fk_apa_permission FOREIGN KEY (permission_id) REFERENCES admin_permission (permission_id),
    CONSTRAINT fk_apa_assigned_by FOREIGN KEY (assigned_by) REFERENCES app_user (user_id),
    CONSTRAINT fk_apa_revoked_by FOREIGN KEY (revoked_by) REFERENCES app_user (user_id),
    CONSTRAINT ck_apa_not_self CHECK (assigned_by <> user_id),
    CONSTRAINT ck_apa_not_self_revoke CHECK (revoked_by IS NULL OR revoked_by <> user_id),
    CONSTRAINT ck_apa_revoked CHECK ((revoked_at IS NULL AND revoked_by IS NULL)
                                  OR (revoked_at IS NOT NULL AND revoked_by IS NOT NULL))
);
CREATE UNIQUE INDEX uq_apa_active ON admin_permission_assignment (
    CASE WHEN revoked_at IS NULL THEN user_id END,
    CASE WHEN revoked_at IS NULL THEN permission_id END);
CREATE INDEX ix_apa_user ON admin_permission_assignment (user_id);
CREATE INDEX ix_apa_permission ON admin_permission_assignment (permission_id);

-- Versioned Terms / Privacy / consent texts
CREATE TABLE policy_document (
    policy_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    policy_type      VARCHAR2(30)  NOT NULL,
    version          VARCHAR2(20)  NOT NULL,
    title_en         VARCHAR2(200) NOT NULL,
    title_sw         VARCHAR2(200) NOT NULL,
    content_en       CLOB          NOT NULL,
    content_sw       CLOB          NOT NULL,
    effective_from   TIMESTAMP WITH TIME ZONE NOT NULL,
    is_current       NUMBER(1)     DEFAULT 0 NOT NULL,
    created_by       NUMBER,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_policy_document PRIMARY KEY (policy_id),
    CONSTRAINT fk_policy_document_creator FOREIGN KEY (created_by) REFERENCES app_user (user_id),
    CONSTRAINT uq_policy_document_version UNIQUE (policy_type, version),
    CONSTRAINT ck_policy_document_type CHECK (policy_type IN ('TERMS', 'PRIVACY', 'DATA_CONSENT')),
    CONSTRAINT ck_policy_document_current CHECK (is_current IN (0, 1))
);
CREATE UNIQUE INDEX uq_policy_document_current ON policy_document (
    CASE WHEN is_current = 1 THEN policy_type END);

CREATE TABLE policy_acceptance (
    acceptance_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER NOT NULL,
    policy_id        NUMBER NOT NULL,
    accepted_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ip_address       VARCHAR2(45),
    user_agent       VARCHAR2(400),
    CONSTRAINT pk_policy_acceptance PRIMARY KEY (acceptance_id),
    CONSTRAINT fk_policy_acceptance_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT fk_policy_acceptance_policy FOREIGN KEY (policy_id) REFERENCES policy_document (policy_id),
    CONSTRAINT uq_policy_acceptance UNIQUE (user_id, policy_id)
);
CREATE INDEX ix_policy_acceptance_policy ON policy_acceptance (policy_id);

-- SMS OTP (AUTH-02/03). Only a hash of the code is stored.
CREATE TABLE otp_code (
    otp_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER        NOT NULL,
    phone            VARCHAR2(20)  NOT NULL,
    purpose          VARCHAR2(30)  NOT NULL,
    code_hash        VARCHAR2(255) NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL,     -- created_at + 2 minutes
    resend_count     NUMBER(2)     DEFAULT 0 NOT NULL,       -- max 3 within the control window
    attempt_count    NUMBER(3)     DEFAULT 0 NOT NULL,
    consumed_at      TIMESTAMP WITH TIME ZONE,
    ip_address       VARCHAR2(45),
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_otp_code PRIMARY KEY (otp_id),
    CONSTRAINT fk_otp_code_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT ck_otp_code_purpose CHECK (purpose IN ('PHONE_VERIFICATION', 'PASSWORD_RESET', 'PHONE_CHANGE')),
    CONSTRAINT ck_otp_code_resend CHECK (resend_count BETWEEN 0 AND 3)
);
CREATE INDEX ix_otp_code_user ON otp_code (user_id, purpose, created_at);
CREATE INDEX ix_otp_code_phone ON otp_code (phone, created_at);

-- Email-link password reset (AUTH-05). SMS resets use otp_code with purpose PASSWORD_RESET.
CREATE TABLE password_reset_token (
    token_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER        NOT NULL,
    token_hash       VARCHAR2(255) NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at          TIMESTAMP WITH TIME ZONE,
    ip_address       VARCHAR2(45),
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_password_reset_token PRIMARY KEY (token_id),
    CONSTRAINT fk_prt_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT uq_prt_token UNIQUE (token_hash)
);
CREATE INDEX ix_prt_user ON password_reset_token (user_id);

-- Server-side sessions; 10-minute inactivity rule uses last_activity_at (AUTH-12).
CREATE TABLE user_session (
    session_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER        NOT NULL,
    token_hash       VARCHAR2(255) NOT NULL,
    ip_address       VARCHAR2(45),
    user_agent       VARCHAR2(400),
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    last_activity_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at       TIMESTAMP WITH TIME ZONE,
    revoke_reason    VARCHAR2(30),
    CONSTRAINT pk_user_session PRIMARY KEY (session_id),
    CONSTRAINT fk_user_session_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT uq_user_session_token UNIQUE (token_hash),
    CONSTRAINT ck_user_session_reason CHECK (revoke_reason IS NULL OR revoke_reason IN
        ('LOGOUT', 'IDLE_TIMEOUT', 'PASSWORD_CHANGED', 'SUSPENDED', 'ADMIN_REVOKED'))
);
CREATE INDEX ix_user_session_user ON user_session (user_id);

-- Login attempts feed rate limiting/lockout (AUTH-13) and security reporting.
