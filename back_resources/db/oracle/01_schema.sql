    requirements_confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Frozen copies taken at submission (PROF-03/04, CV-09, APP-13)
    profile_snapshot        CLOB          NOT NULL,
    cv_snapshot             CLOB          NOT NULL,
    cv_snapshot_file_id     NUMBER        NOT NULL,      -- PDF exactly as the employer sees it
    profile_completion_at_submit NUMBER(5,2) NOT NULL,
    status                  VARCHAR2(20)  DEFAULT 'SUBMITTED' NOT NULL,
    status_changed_by       NUMBER,                      -- set by app with each status change
    status_changed_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    status_remarks          VARCHAR2(1000),
    submitted_at            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    last_edited_at          TIMESTAMP WITH TIME ZONE,
    created_at              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_application PRIMARY KEY (application_id),
    CONSTRAINT uq_application_ref UNIQUE (application_ref),
    CONSTRAINT fk_application_vacancy FOREIGN KEY (vacancy_id) REFERENCES vacancy (vacancy_id),
    CONSTRAINT fk_application_profile FOREIGN KEY (profile_id) REFERENCES job_seeker_profile (profile_id),
    CONSTRAINT fk_application_cv FOREIGN KEY (cv_id) REFERENCES cv (cv_id),
    CONSTRAINT fk_application_cv_file FOREIGN KEY (cv_snapshot_file_id) REFERENCES stored_file (file_id),
    CONSTRAINT fk_application_status_by FOREIGN KEY (status_changed_by) REFERENCES app_user (user_id),
    CONSTRAINT ck_application_status CHECK (status IN ('SUBMITTED', 'IN_REVIEW', 'REJECTED', 'SHORTLISTED')),
    CONSTRAINT ck_application_confirmed CHECK (requirements_confirmed = 1),
    CONSTRAINT ck_application_profile_json CHECK (profile_snapshot IS JSON),
    CONSTRAINT ck_application_cv_json CHECK (cv_snapshot IS JSON)
);
