    CONSTRAINT fk_vacancy_created_by FOREIGN KEY (created_by) REFERENCES app_user (user_id),
    CONSTRAINT ck_vacancy_positions CHECK (number_of_positions > 0),                      -- VAC-09
    CONSTRAINT ck_vacancy_experience CHECK (min_experience_years >= 0),
    CONSTRAINT ck_vacancy_salary CHECK ((salary_min IS NULL OR salary_min >= 0)
        AND (salary_max IS NULL OR salary_max >= 0)
        AND (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min)),
    CONSTRAINT ck_vacancy_salary_period CHECK (salary_period IS NULL OR salary_period IN
